import type { Db } from '../db/adapter';
import { NOT_SYNCED } from './schema';

// Writes the SQL that sets up the matching tables in Supabase.
// The cloud copy is a plain store: it keeps no checks or links of its own (this app decides what is valid),
// it only remembers which rows are newest and when each arrived, so devices can ask "what is new since I last asked?".
// The script can be pasted again after any app update: it only adds what is missing.

interface Col { name: string; type: string }
export interface CloudTable { name: string; columns: Col[]; key: string }

const pgType = (declared: string): string => {
  const t = declared.toUpperCase();
  if (t.includes('INT')) return 'bigint';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'double precision';
  return 'text';
};

export async function cloudTables(db: Db): Promise<CloudTable[]> {
  const names = await db.select<{ name: string; sql: string | null }>("SELECT name, sql FROM sqlite_master WHERE type = 'table' ORDER BY name");
  const out: CloudTable[] = [];
  for (const t of names) {
    if (t.name.startsWith('sqlite_') || t.name.startsWith('_sqlx') || /^search_fts/.test(t.name) || /VIRTUAL TABLE/i.test(t.sql ?? '') || t.name in NOT_SYNCED) continue;
    const cols = await db.select<{ name: string; type: string; pk: number }>(`PRAGMA table_info("${t.name}")`);
    out.push({ name: t.name, key: t.name === 'app_setting' ? 'key' : 'id', columns: cols.map((c) => ({ name: c.name, type: c.type })) });
  }
  return out;
}

const q = (s: string) => `"${s}"`;

export function generateSupabaseSql(tables: CloudTable[], version: number): string {
  const L: string[] = [];
  L.push(
    '-- Book Journal: cloud tables for syncing. Generated by the app; do not edit by hand.',
    '-- Paste this whole file into Supabase > SQL Editor and press Run. It is safe to run again after an app update.',
    `-- Database version: ${version}`,
    '',
    'create table if not exists public.sync_schema (version integer not null);',
    'alter table public.sync_schema enable row level security;',
    'drop policy if exists "read version" on public.sync_schema;',
    'create policy "read version" on public.sync_schema for select to authenticated using (true);',
    '',
    'create table if not exists public.sync_ping (user_id uuid primary key default auth.uid(), at timestamptz not null default now());',
    'alter table public.sync_ping enable row level security;',
    'drop policy if exists "own ping" on public.sync_ping;',
    'create policy "own ping" on public.sync_ping for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));',
    '',
    '-- Stamps each arriving row with the server time, and ignores a row that is not newer than the one already stored.',
    'create or replace function public.sync_guard() returns trigger language plpgsql as $$',
    'begin',
    '  new.synced_at := clock_timestamp();',
    '  new.user_id := auth.uid();',
    "  if tg_op = 'UPDATE' and new.updated_at is not null and old.updated_at is not null and new.updated_at <= old.updated_at then",
    '    return null;',
    '  end if;',
    '  return new;',
    'end;',
    '$$;',
    '',
    '-- Tells the other devices something changed, so they can pick it up straight away.',
    'create or replace function public.sync_ping() returns trigger language plpgsql as $$',
    'begin',
    '  insert into public.sync_ping (user_id, at) values (auth.uid(), now()) on conflict (user_id) do update set at = excluded.at;',
    '  return null;',
    'end;',
    '$$;',
    '',
    'do $$ begin',
    '  alter publication supabase_realtime add table public.sync_ping;',
    'exception when duplicate_object then null;',
    'end $$;',
    '',
  );
  for (const t of tables) {
    const tn = `public.${q(t.name)}`;
    L.push(`-- ${t.name}`);
    L.push(`create table if not exists ${tn} (${q(t.key)} text primary key, user_id uuid not null default auth.uid(), synced_at timestamptz not null default clock_timestamp());`);
    for (const c of t.columns) if (c.name !== t.key) L.push(`alter table ${tn} add column if not exists ${q(c.name)} ${pgType(c.type)};`);
    L.push(
      `create index if not exists ${q(`ix_${t.name}_sync`)} on ${tn} (user_id, synced_at);`,
      `alter table ${tn} enable row level security;`,
      `drop policy if exists "own rows" on ${tn};`,
      `create policy "own rows" on ${tn} for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));`,
      `drop trigger if exists sync_guard on ${tn};`,
      `create trigger sync_guard before insert or update on ${tn} for each row execute function public.sync_guard();`,
      `drop trigger if exists sync_ping on ${tn};`,
      `create trigger sync_ping after insert or update or delete on ${tn} for each statement execute function public.sync_ping();`,
      '',
    );
  }
  L.push('delete from public.sync_schema;', `insert into public.sync_schema (version) values (${version});`, '');
  return L.join('\n');
}
